#Считываем номер цифры, которую ищем 
n = int(input())
num = 0
while True:
    
    # Узнаем, сколько цифр в текущем числе num
    if num < 10:
        d = 1          
    elif num < 100:
        d = 2          
    else:
        d = 3          
        
    # Проверяем, находится ли искомая цифра внутри этого числа 
    if n <= d:
        # Вычисляем, сколько цифр нужно "отрезать" справа от числа num.
        power = d - n
        
        # МАГИЯ МАТЕМАТИКИ (без строк!):
        # 1. 10 ** power — это степень десятки (1, 10, 100 и т.д.)
        # 2. num // (10 ** power) — целочисленное деление "отрезает" ненужные цифры справа.
        # 3. % 10 — оставляет только самую последнюю (правую) цифру из того, что осталось.
        answer = (num // (10 ** power)) % 10
        print(answer)
        break  
    num += 1
